static inline i32 NTC_THERM_ADC_TO_cDegC(u16 adc_value) {
    i32 p1, p2;
    p1 = NTC_THERM_LUT[(adc_value >> 5)];
    p2 = NTC_THERM_LUT[(adc_value >> 5) + 1];
    return p1 - ((p1 - p2) * (adc_value & 0x001F)) / 32;
};